import { basename, join } from 'node:path'
import type { ShellSpec } from './paths'

// Operant's soft two-line prompt for the plain shell terminals it starts itself. It only generates text (the init
// scripts) and the arguments that make a shell read them; nothing here touches the user's own shell files.
// cmd.exe, fish and any other shell are left alone.

export type PromptShell = 'powershell' | 'bash' | 'zsh'

export function promptShellOf(file: string): PromptShell | null {
  const name = basename(file.replace(/\\/g, '/')).toLowerCase().replace(/\.exe$/, '')
  if (name === 'powershell' || name === 'pwsh') return 'powershell'
  if (name === 'bash') return 'bash'
  if (name === 'zsh') return 'zsh'
  return null
}

export interface SoftPromptFile {
  path: string
  content: string
}

export interface SoftPromptLaunch {
  spec: ShellSpec
  // Added to the shell's environment (zsh finds its start-up files through ZDOTDIR).
  env: Record<string, string>
  files: SoftPromptFile[]
}

export interface SoftPromptOptions {
  shell: ShellSpec
  // Operant's data folder; the scripts live in a "shell" folder inside it.
  dataDir: string
  home: string
  // The user's own ZDOTDIR, when they set one.
  zdotdir?: string
}

// Soft 256-colour tones: folder blue, branch green, marker and duration yellow, failure red, connector grey.
export const SOFT_COLOURS = { folder: 110, branch: 114, warn: 222, fail: 174, dim: 244 } as const

// In the templates below, "§{" stands for "${" so the template literals do not interpolate.
const sh = (text: string): string => text.replaceAll('§{', '${')

const POWERSHELL = String.raw`# Operant soft prompt (PowerShell). Generated by Operant; edits are overwritten.
$global:__opLast = -1
$global:__opSeen = $false
$global:__opGit = [bool](Get-Command git -ErrorAction SilentlyContinue)
function global:prompt {
  $ok = $?
  $exitCode = $global:LASTEXITCODE
  try {
    $tl = [string][char]0x256D + [char]0x2500
    $bl = [string][char]0x2570 + [char]0x2500
    $chev = [string][char]0x276F
    $dot = [string][char]0x25CF
    $width = 80
    try { $width = [int]$Host.UI.RawUI.WindowSize.Width } catch {}
    if ($width -lt 20) { $width = 80 }
    $onDisk = ($PWD.Provider.Name -eq 'FileSystem')
    $dir = $PWD.Path
    if ($onDisk) { $dir = $PWD.ProviderPath }
    $homeDir = $HOME
    if ($homeDir) {
      $sep = [string][IO.Path]::DirectorySeparatorChar
      $homeTrim = $homeDir.TrimEnd($sep)
      if ($dir -eq $homeDir -or $dir -eq $homeTrim) { $dir = '~' }
      elseif ($dir.StartsWith($homeTrim + $sep, [StringComparison]::OrdinalIgnoreCase)) { $dir = '~' + $dir.Substring($homeTrim.Length) }
    }
    $branch = ''
    $dirty = $false
    if ($global:__opGit -and $onDisk) {
      try {
        $b = git rev-parse --abbrev-ref HEAD 2>$null
        if ($LASTEXITCODE -eq 0 -and $b) {
          $branch = [string]$b
          $dirty = [bool](git status --porcelain 2>$null | Select-Object -First 1)
        }
      } catch {}
    }
    $dur = ''
    $h = Get-History -Count 1 -ErrorAction SilentlyContinue
    if ($h -and $h.Id -ne $global:__opLast) {
      $global:__opLast = $h.Id
      $s = [int][math]::Floor(($h.EndExecutionTime - $h.StartExecutionTime).TotalSeconds)
      if ($s -ge 3600) { $dur = '{0}h {1}m {2}s' -f [math]::Floor($s / 3600), [math]::Floor(($s % 3600) / 60), ($s % 60) }
      elseif ($s -ge 60) { $dur = '{0}m {1}s' -f [math]::Floor($s / 60), ($s % 60) }
      elseif ($s -ge 3) { $dur = "$($s)s" }
    }
    if ($global:__opSeen) { Write-Host '' }
    $global:__opSeen = $true
    Write-Host $tl -NoNewline -ForegroundColor DarkGray
    Write-Host (' ' + $dir) -NoNewline -ForegroundColor Blue
    $len = 3 + $dir.Length
    if ($branch) {
      Write-Host (' ' + $branch) -NoNewline -ForegroundColor Green
      $len += 1 + $branch.Length
      if ($dirty) {
        Write-Host (' ' + $dot) -NoNewline -ForegroundColor Yellow
        $len += 2
      }
    }
    if ($dur) {
      $pad = $width - $len - $dur.Length - 1
      if ($pad -ge 1) {
        Write-Host (' ' * $pad) -NoNewline
        Write-Host $dur -NoNewline -ForegroundColor Yellow
      }
    }
    Write-Host ''
    Write-Host $bl -NoNewline -ForegroundColor DarkGray
    if ($ok) { Write-Host $chev -NoNewline -ForegroundColor Green } else { Write-Host $chev -NoNewline -ForegroundColor Red }
    return ' '
  } catch {
    return 'PS ' + $PWD.Path + '> '
  } finally {
    $global:LASTEXITCODE = $exitCode
  }
}
`

